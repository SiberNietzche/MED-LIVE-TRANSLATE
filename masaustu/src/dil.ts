export const gecerliDil = (d: unknown): d is ArayuzDili => d === "tr" || d === "en" || d === "kmr";

/** Windows dili Türkçe ise Türkçe, Kürtçe ise Kurmancî, değilse English (yalnızca ilk açılışta). */
export function varsayilanArayuzDili(): ArayuzDili {
  const l = (navigator.languages?.[0] || navigator.language || "tr").toLowerCase();
  if (l.startsWith("tr")) return "tr";
  if (l.startsWith("ku") || l.startsWith("kmr")) return "kmr";
  return "en";
}

export function arayuzDiliAyarla(d: ArayuzDili) {
  etkin = d;
  document.documentElement.lang = d === "kmr" ? "ku" : d;
}
export const arayuzDili = () => etkin;

/** Sözlükten metin; {ad} yer tutucuları doldurulur. Eksikse Türkçesi, o da yoksa anahtar döner. */
export function t(anahtar: string, d: Record<string, string | number> = {}): string {
  const m = SOZLUKLER[etkin][anahtar] ?? TR[anahtar] ?? anahtar;
  return m.replace(/\{(\w+)\}/g, (_, k) => (k in d ? String(d[k]) : `{${k}}`));
}

